/* 当前语言：由 <html lang> / .lang-en 决定（与官网主站同一套机制） */
window.TS_LANG = (function () {
  var el = document.documentElement;
  if (el.classList.contains('lang-en')) return 'en';
  return (el.getAttribute('lang') || 'zh').toLowerCase().indexOf('en') === 0 ? 'en' : 'zh';
})();

/* 取文案：T('board.cols.todo')；缺键时返回键名本身，便于在页面上直接看出漏翻 */
window.T = function (path) {
  var dict = window.TS_I18N[window.TS_LANG] || window.TS_I18N.zh;
  var cur = path.split('.').reduce(function (acc, k) {
    return (acc && typeof acc === 'object') ? acc[k] : undefined;
  }, dict);
  if (cur === undefined) {
    var zh = path.split('.').reduce(function (acc, k) {
      return (acc && typeof acc === 'object') ? acc[k] : undefined;
    }, window.TS_I18N.zh);
    return zh === undefined ? path : zh;
  }
  return cur;
};
